#!/usr/bin/env python3
"""Generate the src ROM's synthesizable read logic from a $readmemh image."""

import argparse
from pathlib import Path
import re


NOP = 0x00000013


def read_words(image, depth):
    if depth <= 0:
        raise ValueError("ROM depth must be positive")

    words = {}
    index = 0
    tokens = re.sub(r"/\*.*?\*/|//[^\n]*", " ", image, flags=re.DOTALL).split()
    for token in tokens:
        is_address = token.startswith("@")
        digits = token[1:] if is_address else token
        if not re.fullmatch(r"[0-9a-fA-F]+(?:_[0-9a-fA-F]+)*", digits):
            raise ValueError(f"invalid hex token: {token!r}")
        value = int(digits, 16)

        if is_address:
            index = value
        if index >= depth:
            raise ValueError(f"word address 0x{index:x} is outside the {depth}-word ROM")
        if not is_address:
            if value > 0xffffffff:
                raise ValueError(f"word at 0x{index:x} exceeds 32 bits")
            words[index] = value
            index += 1
    return words


def gen_rom_case(words, depth):
    width = max(1, (depth - 1).bit_length())
    address = f"s_axi_araddr[{width + 1}:2]" if depth > 1 else "1'b0"
    entries = "".join(
        f"                    {width}'d{index}: r_data_r <= 32'h{value:08x};\n"
        for index, value in sorted(words.items()) if value != NOP
    )

    return f"""// Generated by gen_rom_case.py. ROM depth: {depth} words.
    always @(posedge clk or posedge reset) begin
        if (reset) begin
            r_data_r  <= 32'h{NOP:08x};
            r_valid_r <= 1'b0;
        end else begin
            if (s_axi_arvalid && !r_valid_r) begin
                r_valid_r <= 1'b1;
                case ({address})
{entries}                    default: r_data_r <= 32'h{NOP:08x}; // NOP
                endcase
            end
            if (r_valid_r && s_axi_rready)
                r_valid_r <= 1'b0;
        end
    end
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", type=Path, help="$readmemh file with word-addressed @ markers")
    parser.add_argument("depth", type=int, nargs="?", default=2048, help="ROM depth in 32-bit words")
    parser.add_argument("-o", "--output", type=Path, help="write the generated logic to a Verilog include")
    args = parser.parse_args()

    try:
        words = read_words(args.input.read_text(encoding="utf-8-sig"), args.depth)
        case = gen_rom_case(words, args.depth)
        if args.output is None:
            print(case, end="")
        else:
            args.output.write_text(case, encoding="ascii")
    except (OSError, ValueError) as error:
        parser.error(str(error))


if __name__ == "__main__":
    main()
